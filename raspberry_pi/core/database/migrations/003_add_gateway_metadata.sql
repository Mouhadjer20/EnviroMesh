-- Migration 003: Add gateway metadata columns and duplicate-detection table
-- Applies to: sensor_telemetry (hypertable), new processed_messages table
--
-- Run after 001_create_registry.sql and 002_create_telemetry.sql (or
-- 001_create_telemetry.sql in existing deployments that used the single-file naming).
--
-- SAFE TO RUN MULTIPLE TIMES (all statements use IF NOT EXISTS / OR IGNORE).

-- ── 1. Add gateway metadata columns to sensor_telemetry ──────────────────────
-- Nullable so existing rows (from the single-Pi deployment) remain valid.

ALTER TABLE sensor_telemetry
    ADD COLUMN IF NOT EXISTS message_id          TEXT,
    ADD COLUMN IF NOT EXISTS gateway_id          VARCHAR(20),
    ADD COLUMN IF NOT EXISTS gateway_received_at TIMESTAMPTZ;

-- Non-unique index for dedup lookups (hypertable cannot have a unique index on
-- a non-partitioning column — see processed_messages below for dedup enforcement).
CREATE INDEX IF NOT EXISTS idx_telemetry_message_id
    ON sensor_telemetry (message_id)
    WHERE message_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_telemetry_gateway_id
    ON sensor_telemetry (gateway_id)
    WHERE gateway_id IS NOT NULL;

-- ── 2. processed_messages — authoritative dedup table ────────────────────────
-- Normal PostgreSQL table (not a hypertable) so PRIMARY KEY works without
-- TimescaleDB unique-index restrictions.
-- Retention: rows older than 7 days can be purged by a maintenance job.

CREATE TABLE IF NOT EXISTS processed_messages (
    message_id   TEXT         PRIMARY KEY,
    device_id    VARCHAR(20)  NOT NULL,
    gateway_id   VARCHAR(20),
    processed_at TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_processed_messages_processed_at
    ON processed_messages (processed_at DESC);

-- ── 3. Helpful comment ───────────────────────────────────────────────────────
COMMENT ON TABLE processed_messages IS
    'Deduplication registry. A message_id present here has already been '
    'written to sensor_telemetry and must not be inserted again.';

COMMENT ON COLUMN sensor_telemetry.message_id IS
    'Stable UUID generated by the gateway (uuid5 for LoRa, uuid4 for Wi-Fi). '
    'Used for idempotent inserts via the processed_messages dedup table.';

COMMENT ON COLUMN sensor_telemetry.gateway_id IS
    'Identifier of the gateway that received and forwarded this reading (e.g. GW01).';

COMMENT ON COLUMN sensor_telemetry.gateway_received_at IS
    'UTC timestamp when the gateway received the packet from the ESP32 node.';

